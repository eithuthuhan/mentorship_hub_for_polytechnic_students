def normalize_language(language: str | None) -> str:
    if language in TRANSLATIONS:
        return language
    if not language:
        return 'English'
    value = str(language).strip().lower()
    if value in ('myanmar', 'burmese', 'mm', 'မြန်မာ'):
        return 'Myanmar'
    if value in ('japanese', 'jp', 'ja', '日本語'):
        return 'Japanese'
    return 'English'


def tr(language: str | None, key: str, default: str | None = None) -> str:
    lang = normalize_language(language)
    return TRANSLATIONS.get(lang, {}).get(key, default or key)
